"""Content fingerprint of the framework sources.

Why: check_artifacts decided "is DuiLib.lib stale?" by comparing the newest source
mtime against the lib's mtime. Every injection test in this project restores a source
file afterwards, which refreshes its mtime without changing a byte -- so the gate
reported "lib is older than the sources" on every single round that touched a header,
and each time the fix was to rebuild for nothing.

The honest question is "was this lib built from the current sources?", which is about
CONTENT, not timestamps. This tool hashes the content:

    python tools/source_fingerprint.py --write    # record current sources
    python tools/source_fingerprint.py            # print current fingerprint
    python tools/source_fingerprint.py --check    # compare against the record

The record lives at tools/source_fingerprint.txt and contains one line per source
(files are sorted so the file is diffable). The hash covers the framework tree only
(DuiLib/**, excluding build output), because that is what DuiLib.lib is built from.

Limitation stated up front: this detects "sources changed since the fingerprint was
written". It cannot know whether the lib on disk was built after the last change --
that is what the build step itself must guarantee. So the gate checks two things:
fingerprint changed -> ask for a rebuild; fingerprint unchanged -> the lib's mtime is
irrelevant.
"""
import argparse
import hashlib
import pathlib
import sys
import sys as _sys, pathlib as _pl
_sys.path.insert(0, str(_pl.Path(__file__).resolve().parent))
# [R87] shared skip set; this file held a 6th copy
from scan_scope import SKIP_DIRS

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Two trees are fingerprinted: the framework (what DuiLib.lib is built from) and the
# demo app (what Win8Metro.exe is built from). They are recorded separately because
# changing only a Demo file must not demand a framework rebuild, and vice versa.
TREES = {
    'framework': (ROOT / 'DuiLib', ROOT / 'tools' / 'source_fingerprint.txt'),
    'demos':     (ROOT / 'Demos',  ROOT / 'tools' / 'source_fingerprint_demos.txt'),
}

SKIP_PARTS = SKIP_DIRS | {'.vs'}
SUFFIXES = {'.cpp', '.h', '.hpp', '.c', '.cxx', '.vcxproj', '.filters', '.rc', '.def'}


def iter_sources(root):
    for f in sorted(root.rglob('*')):
        if not f.is_file() or f.suffix.lower() not in SUFFIXES:
            continue
        if {x.lower() for x in f.relative_to(root).parts} & SKIP_PARTS:
            continue
        # A vendored third-party file still counts: it is compiled into the binary.
        yield f


def digest(path):
    h = hashlib.sha256()
    with open(path, 'rb') as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def current_map(root):
    out = {}
    for f in iter_sources(root):
        out[str(f.relative_to(ROOT)).replace(chr(92), '/')] = digest(f)
    return out


def read_record(record):
    if not record.is_file():
        return None
    out = {}
    for line in record.read_text(encoding='utf-8').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        parts = line.split(' ', 1)
        if len(parts) == 2:
            out[parts[1].strip()] = parts[0].strip()
    return out


def write_record(record, m):
    lines = ['# sha256 <path>  -- generated by tools/source_fingerprint.py --write']
    for path in sorted(m):
        lines.append('%s %s' % (m[path], path))
    record.write_text(chr(10).join(lines) + chr(10), encoding='utf-8')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true', help='record the current fingerprint')
    ap.add_argument('--check', action='store_true', help='compare and report differences')
    ap.add_argument('--tree', default='framework', choices=sorted(TREES),
                    help='which tree to fingerprint: framework (DuiLib) or demos (Win8Metro)')
    args = ap.parse_args()

    src_root, record = TREES[args.tree]
    m = current_map(src_root)
    if not m:
        print('[FAIL] zero source files found under %s' % src_root)
        return 2
    print('[INFO] sources=%d' % len(m))

    if args.write:
        write_record(record, m)
        print('[PASS] fingerprint recorded: %s (%s)' % (record.name, args.tree))
        return 0

    old = read_record(record)
    if old is None:
        print('[WARN] no fingerprint recorded yet (%s missing)' % record.name)
        print('       run: python tools/source_fingerprint.py --write')
        return 0

    added = sorted(set(m) - set(old))
    removed = sorted(set(old) - set(m))
    changed = sorted(p for p in set(m) & set(old) if m[p] != old[p])

    if not (added or removed or changed):
        print('[PASS] sources match the recorded fingerprint (%d files)' % len(m))
        return 0

    print('[FAIL] sources changed since the fingerprint was recorded:')
    for p in changed[:15]:
        print('       modified: %s' % p)
    for p in added[:15]:
        print('       added   : %s' % p)
    for p in removed[:15]:
        print('       removed : %s' % p)
    if args.check:
        print('       rebuild DuiLib, then re-record:')
        # Forward slashes on purpose: a backslash-D inside a normal string is a
        # SyntaxWarning on stderr, and PowerShell's Stop preference turns that into a
        # terminating error for the caller.
        print('         msbuild DuiLib/DuiLib.vcxproj /t:Rebuild ...')
        print('         python tools/source_fingerprint.py --write')
    return 1


if __name__ == '__main__':
    sys.exit(main())
