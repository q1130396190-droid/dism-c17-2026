"""gen_skin_pack.py -- 把皮肤目录打包成可直接编译进 DLL 的 C++ 源文件。

为什么用生成源文件而不是 Windows 资源(.rc):
  .rc 里的二进制资源要按 名字+类型 用 FindResource 查找，而我们需要
  "按相对路径查一个 XML 文本"，路径含 '/' 且应大小写不敏感；
  资源名不支持这些语义。直接生成 C++ 数组 + 一张路径表，
  查找是纯内存比对，没有 API 语义干扰，也便于做"零资源自检"。

用法:
  python gen_skin_pack.py --skin <皮肤目录> --slot light --out <输出.cpp>

退出码: 0 成功, 2 输入问题(目录不存在/零文件)
"""
import argparse
import io
import os
import sys


def collect(skin_dir):
    """收集皮肤目录下所有需要打包的文件。

    只收 .xml 与图片：.xml 是皮肤结构，图片是皮肤引用的位图。
    显式跳过 .ico/.txt 等非渲染必需文件，避免把无关内容带进发布包。
    """
    keep_ext = ('.xml', '.png', '.jpg', '.jpeg', '.bmp', '.gif')
    out = []
    for root, _dirs, files in os.walk(skin_dir):
        for f in sorted(files):
            if not f.lower().endswith(keep_ext):
                continue
            full = os.path.join(root, f)
            rel = os.path.relpath(full, skin_dir).replace('\\', '/')
            out.append((rel, full))
    out.sort(key=lambda kv: kv[0])
    return out


def emit_bytes(fh, name, data):
    fh.write('static const unsigned char %s[] = {\n' % name)
    # 每行 20 字节：既能压住文件行数，也不会让单行过长影响 diff 可读性
    for i in range(0, len(data), 20):
        chunk = data[i:i + 20]
        fh.write('    ' + ','.join('0x%02X' % b for b in chunk) + ',\n')
    fh.write('};\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--skin', required=True, help='皮肤目录（含 Main.xml 与 pages/）')
    ap.add_argument('--slot', required=True, help='槽位标识：light / dark')
    ap.add_argument('--out', required=True, help='输出 .cpp 路径')
    args = ap.parse_args()

    if not os.path.isdir(args.skin):
        print('[FATAL] skin dir not found: %s' % args.skin, file=sys.stderr)
        return 2

    files = collect(args.skin)
    if not files:
        # 零输入必须硬失败：空皮肤包加载后界面全空白，而且不会有任何报错
        print('[FATAL] no skin files under %s -- refusing to emit an empty pack'
              % args.skin, file=sys.stderr)
        return 2

    slot = args.slot
    with io.open(args.out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// AUTO-GENERATED by tools/gen_skin_pack.py -- do not edit.\n')
        fh.write('// slot=%s  files=%d  source=%s\n\n' % (slot, len(files), args.skin))
        fh.write('#include "SkinThemeDll.h"\n\n')
        fh.write('namespace skinpack_%s {\n\n' % slot)

        for n, (rel, full) in enumerate(files):
            data = open(full, 'rb').read()
            emit_bytes(fh, 'k_%d' % n, data)
            fh.write('\n')

        fh.write('struct TEntry { const wchar_t* pszName; const unsigned char* pData;\n')
        fh.write('                unsigned int cbData; };\n\n')
        fh.write('static const TEntry s_entries[] = {\n')
        for n, (rel, _full) in enumerate(files):
            cb = os.path.getsize(files[n][1])
            fh.write('    { L"%s", k_%d, %du },\n' % (rel, n, cb))
        fh.write('};\n\n')
        fh.write('}  // namespace skinpack_%s\n\n' % slot)
        # 对外只暴露函数：跨 TU 引用 const 对象会因内部链接而 LNK2001。
        # 返回函数让链接语义明确，也不依赖 C++17 inline variable。
        fh.write('const void* SkinPack_%s_Entries(void)\n{\n' % slot)
        fh.write('    return static_cast<const void*>(skinpack_%s::s_entries);\n}\n\n' % slot)
        fh.write('int SkinPack_%s_Count(void)\n{\n' % slot)
        fh.write('    return %d;\n}\n' % len(files))
    print('[OK] %s: %d file(s) -> %s' % (slot, len(files), args.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
